import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import 'package:lucide_icons_flutter/lucide_icons.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import '../../core/constants/app_colors.dart';
import '../../core/constants/app_enums.dart';
import '../../core/utils/formatters.dart';
import '../../providers/sales_provider.dart';
import '../../providers/product_provider.dart';
import '../../providers/expense_provider.dart';
import '../shared/stat_card.dart';

class ReportsScreen extends StatelessWidget {
  const ReportsScreen({Key? key}) : super(key: key);

  Future<void> _exportPdfReport(
    BuildContext context, {
    required double grossRevenue,
    required double totalCogs,
    required double grossProfit,
    required double totalExpenses,
    required double netProfit,
    required double totalGst,
    required int orderCount,
  }) async {
    final pdf = pw.Document();

    pdf.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(12 * PdfPageFormat.mm),
        build: (pw.Context context) {
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Text(
                        'RETAILFLOW POS - FINANCIAL P&L & GST REPORT',
                        style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold),
                      ),
                      pw.Text('Generated: ${Formatters.dateTime(DateTime.now())}',
                          style: const pw.TextStyle(fontSize: 9)),
                    ],
                  ),
                  pw.Text('GSTIN: 29AABCU9603R1ZM',
                      style: pw.TextStyle(fontSize: 9, fontWeight: pw.FontWeight.bold)),
                ],
              ),
              pw.Divider(thickness: 1),
              pw.SizedBox(height: 8),

              pw.Text('1. Financial Executive Summary',
                  style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold)),
              pw.SizedBox(height: 6),

              pw.Table(
                border: pw.TableBorder.all(color: PdfColors.grey300),
                children: [
                  _buildPdfTableRow('Metric', 'Amount (INR)', isHeader: true),
                  _buildPdfTableRow('Gross Revenue (Sales)', Formatters.currency(grossRevenue)),
                  _buildPdfTableRow('Cost of Goods Sold (COGS)', '- ${Formatters.currency(totalCogs)}'),
                  _buildPdfTableRow('Gross Operating Profit', Formatters.currency(grossProfit)),
                  _buildPdfTableRow('Store Operating Expenses', '- ${Formatters.currency(totalExpenses)}'),
                  _buildPdfTableRow('Estimated Net Profit', Formatters.currency(netProfit), isHighlight: true),
                  _buildPdfTableRow('Output GST Tax Liability', Formatters.currency(totalGst)),
                  _buildPdfTableRow('Total Completed Orders', '$orderCount Transactions'),
                ],
              ),
              pw.SizedBox(height: 16),
              pw.Text('Official Store Accounting Record • Generated by RetailFlow Android POS',
                  style: const pw.TextStyle(fontSize: 8)),
            ],
          );
        },
      ),
    );

    await Printing.layoutPdf(
      onLayout: (format) async => pdf.save(),
      name: 'RetailFlow_Financial_Report.pdf',
    );
  }

  static pw.TableRow _buildPdfTableRow(String col1, String col2,
      {bool isHeader = false, bool isHighlight = false}) {
    return pw.TableRow(
      decoration: isHeader
          ? const pw.BoxDecoration(color: PdfColors.grey200)
          : (isHighlight
              ? const pw.BoxDecoration(color: PdfColors.indigo50)
              : const pw.BoxDecoration()),
      children: [
        pw.Padding(
          padding: const pw.EdgeInsets.all(6),
          child: pw.Text(
            col1,
            style: pw.TextStyle(
              fontSize: 9,
              fontWeight: isHeader || isHighlight ? pw.FontWeight.bold : pw.FontWeight.normal,
            ),
          ),
        ),
        pw.Padding(
          padding: const pw.EdgeInsets.all(6),
          child: pw.Text(
            col2,
            textAlign: pw.TextAlign.right,
            style: pw.TextStyle(
              fontSize: 9,
              fontWeight: isHeader || isHighlight ? pw.FontWeight.bold : pw.FontWeight.normal,
            ),
          ),
        ),
      ],
    );
  }

  @override
  Widget build(BuildContext context) {
    final salesProv = context.watch<SalesProvider>();
    final productProv = context.watch<ProductProvider>();
    final expProv = context.watch<ExpenseProvider>();

    final completedSales =
        salesProv.sales.where((s) => s.status == SaleStatus.completed).toList();

    final double grossRevenue =
        completedSales.fold(0.0, (sum, s) => sum + s.totalAmount);
    final double totalGst =
        completedSales.fold(0.0, (sum, s) => sum + s.taxAmount);
    final double totalDiscount =
        completedSales.fold(0.0, (sum, s) => sum + s.discountAmount);

    // Compute approximate COGS based on sold items
    double totalCogs = 0.0;
    for (final sale in completedSales) {
      for (final item in sale.items) {
        final p = productProv.products.where((prod) => prod.id == item.productId).firstOrNull;
        if (p != null) {
          totalCogs += (p.costPrice * item.quantity);
        } else {
          totalCogs += (item.unitPrice * 0.65 * item.quantity);
        }
      }
    }

    final double grossProfit = (grossRevenue - totalGst - totalCogs).clamp(0.0, double.infinity);
    final double totalExpenses = expProv.totalExpenses;
    final double netProfit = grossProfit - totalExpenses;

    final isWide = MediaQuery.of(context).size.width >= 700;

    return Scaffold(
      backgroundColor: AppColors.background,
      body: SingleChildScrollView(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            // Header & PDF Export Button
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                const Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      'Financial & GST Tax Reports',
                      style: TextStyle(
                        fontSize: 18,
                        fontWeight: FontWeight.w800,
                        color: AppColors.slate900,
                      ),
                    ),
                    Text(
                      'Profit & Loss, GST Liability, and Store Balance sheet',
                      style: TextStyle(fontSize: 12, color: AppColors.slate500),
                    ),
                  ],
                ),
                ElevatedButton.icon(
                  onPressed: () => _exportPdfReport(
                    context,
                    grossRevenue: grossRevenue,
                    totalCogs: totalCogs,
                    grossProfit: grossProfit,
                    totalExpenses: totalExpenses,
                    netProfit: netProfit,
                    totalGst: totalGst,
                    orderCount: completedSales.length,
                  ),
                  icon: const Icon(LucideIcons.fileText, size: 16),
                  label: const Text('Export PDF'),
                  style: ElevatedButton.styleFrom(
                    backgroundColor: AppColors.primary,
                    padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 10),
                    shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(10)),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 16),

            // Financial KPIs Grid
            GridView.count(
              crossAxisCount: isWide ? 4 : 2,
              crossAxisSpacing: 12,
              mainAxisSpacing: 12,
              shrinkWrap: true,
              physics: const NeverScrollableScrollPhysics(),
              childAspectRatio: 1.35,
              children: [
                StatCard(
                  title: 'Gross Revenue',
                  value: Formatters.currency(grossRevenue),
                  subtitle: '${completedSales.length} Total Invoices',
                  icon: LucideIcons.dollarSign,
                  iconColor: AppColors.primary,
                  iconBgColor: AppColors.primaryMuted,
                ),
                StatCard(
                  title: 'Gross Profit',
                  value: Formatters.currency(grossProfit),
                  subtitle: 'Revenue minus COGS',
                  icon: LucideIcons.trendingUp,
                  iconColor: AppColors.success,
                  iconBgColor: AppColors.successMuted,
                ),
                StatCard(
                  title: 'Net Profit',
                  value: Formatters.currency(netProfit),
                  subtitle: 'After ₹${totalExpenses.toStringAsFixed(0)} expenses',
                  icon: LucideIcons.pieChart,
                  iconColor: const Color(0xFF9333EA),
                  iconBgColor: const Color(0xFFFAF5FF),
                ),
                StatCard(
                  title: 'Output GST Tax',
                  value: Formatters.currency(totalGst),
                  subtitle: 'CGST + SGST collected',
                  icon: LucideIcons.receipt,
                  iconColor: const Color(0xFF2563EB),
                  iconBgColor: const Color(0xFFEFF6FF),
                ),
              ],
            ),
            const SizedBox(height: 20),

            // Itemized P&L Ledger Card
            Container(
              padding: const EdgeInsets.all(16),
              decoration: BoxDecoration(
                color: Colors.white,
                borderRadius: BorderRadius.circular(16),
                border: Border.all(color: AppColors.border),
              ),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  const Text(
                    'Profit & Loss Statement Breakdown',
                    style: TextStyle(fontSize: 14, fontWeight: FontWeight.bold, color: AppColors.slate900),
                  ),
                  const SizedBox(height: 12),

                  _buildReportRow('1. Gross Sales Revenue', Formatters.currency(grossRevenue)),
                  _buildReportRow('2. Total Discounts Allowed', '- ${Formatters.currency(totalDiscount)}', isRed: true),
                  _buildReportRow('3. Output GST Tax Liability', Formatters.currency(totalGst)),
                  _buildReportRow('4. Cost of Goods Sold (COGS)', '- ${Formatters.currency(totalCogs)}', isRed: true),
                  const Divider(height: 16, color: AppColors.border),
                  _buildReportRow('5. Gross Profit', Formatters.currency(grossProfit), isBold: true),
                  _buildReportRow('6. Operating Costs & Expenses', '- ${Formatters.currency(totalExpenses)}', isRed: true),
                  const Divider(height: 16, color: AppColors.border),
                  _buildReportRow(
                    '7. Net Store Profit',
                    Formatters.currency(netProfit),
                    isBold: true,
                    isHighlight: true,
                  ),
                ],
              ),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildReportRow(String label, String value,
      {bool isBold = false, bool isRed = false, bool isHighlight = false}) {
    return Container(
      padding: const EdgeInsets.symmetric(vertical: 6, horizontal: 8),
      decoration: BoxDecoration(
        color: isHighlight ? AppColors.primaryMuted : Colors.transparent,
        borderRadius: BorderRadius.circular(8),
      ),
      child: Row(
        mainAxisAlignment: MainAxisAlignment.spaceBetween,
        children: [
          Text(
            label,
            style: TextStyle(
              fontSize: 12.5,
              fontWeight: isBold ? FontWeight.bold : FontWeight.w500,
              color: isHighlight ? AppColors.primaryDark : AppColors.slate700,
            ),
          ),
          Text(
            value,
            style: TextStyle(
              fontSize: 13,
              fontWeight: isBold ? FontWeight.bold : FontWeight.w600,
              color: isRed
                  ? AppColors.danger
                  : (isHighlight ? AppColors.primaryDark : AppColors.slate900),
            ),
          ),
        ],
      ),
    );
  }
}
